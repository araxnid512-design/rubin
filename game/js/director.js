  function needs(S) {
    const out = [];
    if (S.st.food < S.st.people * 0.6) out.push({ tags: ['food', 'harvest', 'trade'], k: 2, why: 'Амбары пустеют: Летописец чаще думает о еде.' });
    if (S.st.hp < 45) out.push({ tags: ['healing'], k: 2, why: 'Герой изранен: в ходу лекари и баня.' });
    if (S.st.sus > 55) out.push({ tags: ['faith', 'intrigue'], k: 1.7, why: 'Подозрение высоко: Око присматривается.' });
    if (S.st.gold < 10) out.push({ tags: ['trade', 'money'], k: 1.6, why: 'Казна пуста: в ходу торговля.' });
    if (Object.keys(S.inv).length >= 4) out.push({ tags: ['invention', 'workshop'], k: 1.4, why: 'Мастерских много: о них говорят.' });
    return out;
  }

  function kindFactor(kind, tension) {
    if (kind === 'threat') return 0.25 + tension * 0.26;
    if (kind === 'calm') return 1.7 - tension * 0.13;
    if (kind === 'opp') return 1.35 - tension * 0.06;
    return 1;
  }

  // Подбор иллюстрации: совпадение тегов, сезон, свежесть (давно не показывали).
  function pickArt(tags, S, rng, season) {
    const ART = R.ART;
    const sTag = SEASON_TAG[season];
    const recent = S.artRecent || [];
    let best = null, bestScore = -1e9;
    for (const sc of ART.SCENES) {
      let score = 0;
      for (const t of tags) if (sc.tags.indexOf(t) >= 0) score += 2;
      if (sc.tags.indexOf(sTag) >= 0) score += 1.5;
      for (const o of SEASON_TAG) if (o !== sTag && sc.tags.indexOf(o) >= 0) score -= 1.6;
      if (sc.tags.indexOf('ending') >= 0 && tags.indexOf('ending') < 0) score -= 6;
      if (sc.tags.indexOf('home') >= 0 && tags.indexOf('home') < 0 && tags.indexOf('dream') < 0) score -= 6;
      const ri = recent.indexOf(sc.id);
      if (ri >= 0) score -= 5 - ri * 0.3;
      if (!(S.seenArt && S.seenArt[sc.id])) score += 0.6;
      score += rng.next() * 1.4;
      if (score > bestScore) { bestScore = score; best = sc; }
    }
    return best.id;
  }

  function generate(S, rng, h) {
    const t0 = performance.now();
    const season = h.season(), act = h.act();
    const g = {
      rng, season,
      m: () => R.nameM(rng), f: () => R.nameF(rng), nick: () => R.nick(rng),
      int: (a, b) => rng.int(a, b),
      invName: () => { const ids = Object.keys(S.inv); const inv = R.BOOK.INV.find((x) => x.id === rng.pick(ids)); return inv ? inv.name : 'Мельница'; },
      nextBeat: () => { const nb = h.nextBeat(); return nb ? nb.title.toLowerCase() : 'перемены'; },
    };

    let tpl = null, reason = [], top = [], cands = 0, follow = null;
    const qi = S.queue.findIndex((q) => q.week <= S.week);
    if (qi >= 0) {
      follow = S.queue.splice(qi, 1)[0];
      tpl = byId[follow.id];
      reason.push('Продолжение старой истории: Летописец помнит ваши прошлые решения.');
    }
    if (!tpl) {
      const nd = needs(S);
      const theme = ACT_THEME[act] || ACT_THEME[4];
      const pool = T.filter((t) => !t.follow && t.acts.indexOf(act) >= 0 && (!t.season || t.season.indexOf(season) >= 0) &&
        (!t.cond || t.cond(S, h)) && !(t.once && S.used[t.id]) && S.recent.indexOf(t.id) < 0);
      cands = pool.length;
      const weight = (t) => {
        let w = (t.w || 1) * kindFactor(t.kind, S.tension);
        if (t.tags.some((x) => theme.tags.indexOf(x) >= 0)) w *= theme.k;
        for (const n of nd) if (t.tags.some((x) => n.tags.indexOf(x) >= 0)) w *= n.k;
        if (t.season) w *= 1.6;
        return w;
      };
      const scored = pool.map((t) => ({ t, w: weight(t) }));
      const tot = scored.reduce((a, b) => a + b.w, 0) || 1;
      scored.sort((a, b) => b.w - a.w);
      top = scored.slice(0, 3).map((x) => ({ title: x.t.id === 'holiday' ? HOLIDAYS[season] : x.t.title, p: Math.round((x.w / tot) * 100) }));
      const picked = rng.weighted(scored, (x) => x.w);
      tpl = picked ? picked.t : byId.fish;
      if (tpl.kind === 'threat' && S.tension >= 5) reason.push(`Напряжение ${S.tension}/10: спокойствие затянулось, пора испытанию.`);
      else if ((tpl.kind === 'calm' || tpl.kind === 'opp') && S.tension <= 2) reason.push('После бури Летописец даёт передышку.');
      else reason.push(`Напряжение ${S.tension}/10, выбран тип «${KIND_NAME[tpl.kind]}».`);
      if (tpl.tags.some((x) => theme.tags.indexOf(x) >= 0)) reason.push(theme.why);
      for (const n of nd) if (tpl.tags.some((x) => n.tags.indexOf(x) >= 0)) reason.push(n.why);
      if (tpl.season) reason.push(`Сезон: ${R.BOOK.SEASONS[season].toLowerCase()}.`);
    }

    const vars = Object.assign({}, tpl.vars ? tpl.vars(g) : {}, follow && follow.vars ? follow.vars : {});
    const parts = [];
    if (rng.chance(0.55)) parts.push(rng.pick(OPENERS[season]));
    parts.push(R.expand(rng.pick(tpl.tx), vars, rng));
    let text = parts.join(' ');
    if (tpl.kind === 'pop' || rng.chance(0.18)) text += '\n\n' + rng.pick(MONO);

    S.recent = [tpl.id].concat(S.recent).slice(0, 10);
    if (tpl.once) S.used[tpl.id] = 1;
    const prevTension = S.tension;
    S.tension = tpl.kind === 'threat' ? Math.max(0, S.tension - 6) : Math.min(10, S.tension + (tpl.kind === 'calm' ? 2 : 1));

    const art = pickArt(tpl.tags, S, rng, season);
    const ms = performance.now() - t0;
    return {
      type: 'event', tid: tpl.id, art, vars,
      label: 'Летописец · ' + KIND_NAME[tpl.kind],
      title: R.expand(tpl.title, vars, rng),
      text,
      ch: tpl.ch.map((c, i) => ({ i, t: R.expand(c.t, vars, rng) })),
      dir: { ms, cands, top, reason, tension: prevTension, kind: tpl.kind },
    };
  }

